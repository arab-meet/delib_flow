#!/usr/bin/env python3
"""Write the benchmark tables from summary.json, so that no number is copied by hand.
usage: tables.py <results dir>   writes <results dir>/tables_summary.txt and <results dir>/tables.tex
Run analyze.py and localization.py on the same directory first."""
import json
import sys

FAULTS = [
    ('planning', 'Planning failure'),
    ('grasp', 'Grasp failure'),
    ('nav', 'Navigation failure'),
    ('none', 'No injection'),
]
VARIANTS = [
    ('hierarchical', 'Hierarchical'),
    ('hierarchical_clear', 'Hierarchical + clear view'),
    ('flat_retry', 'Flat retry x3'),
    ('flat_retry9', 'Flat retry x9'),
    ('no_recovery', 'No recovery'),
    ('api', 'API script, no retries'),
]


def num(x, f='.0f', dash='-'):
    return dash if x is None else format(x, f)


def main():
    root = sys.argv[1]
    s = json.load(open(f'{root}/summary.json'))
    loc = json.load(open(f'{root}/localization.json'))
    md = [
        '# Failure-injection benchmark tables',
        '',
        'Generated by `tables.py`. TIAGo in Gazebo Harmonic, p=0.5 per goal, success means the box rose at least',
        '0.10 m in Gazebo. Intervals are Wilson 95%. Times include other jobs on a shared machine.',
        '',
        '## Success, retries and time',
        '',
        'fault | variant | success | 95% CI | leaf failures | mission restarts | recovery s | wall s (all) | wall s (success)',
        '---|---|---|---|---|---|---|---|---',
    ]
    for f, fname in FAULTS:
        for v, vname in VARIANTS:
            r = s.get(f'{f}/{v}')
            if r:
                md.append(
                    f"{fname} | {vname} | {r['success']}/{r['n']} ({100 * r['rate']:.0f}%) | "
                    f"{100 * r['ci'][0]:.0f}-{100 * r['ci'][1]:.0f}% | {r['leaf']:.2f} | {r['restarts']:.2f} | "
                    f"{num(r['recovery'], '.1f')} | {r['wall']:.0f} | {num(r['wall_ok'])}"
                )
    md += [
        '',
        '## What the mission log names when a mission fails',
        '',
        'fault | variant | failed trials | median candidates | reports',
        '---|---|---|---|---',
    ]
    for f, fname in FAULTS:
        for v, vname in VARIANTS:
            r = loc.get(f'{v}/{f}')
            if r:
                reports = ', '.join(f'{k} {n}' for k, n in r['reports'].items())
                md.append(
                    f"{fname} | {vname} | {r['failed']} | {r['median_candidates']:g} | {reports}"
                )
    open(f'{root}/tables_summary.txt', 'w').write('\n'.join(md) + '\n')

    def cell(f, v):
        r = s[f'{f}/{v}']
        return f"{r['success']}/{r['n']}"

    tex = ['% Generated by experiments/tables.py. Do not edit numbers by hand.']
    tex += ['% robustness rows']
    for f, fname in FAULTS:
        tex.append(
            f"{fname} & {cell(f, 'no_recovery')} & {cell(f, 'flat_retry')} & {cell(f, 'hierarchical')} \\\\"
        )
    tex += ['% ablation rows, pooled over the planning, grasp and navigation faults']
    three = ('planning', 'grasp', 'nav')
    for v, vname in VARIANTS:
        rs = [s.get(f'{f}/{v}') for f in three]
        have = [r for r in rs if r]
        k, n = sum(r['success'] for r in have), sum(r['n'] for r in have)
        wall = sum(r['wall'] * r['n'] for r in have) / n
        rec_n = sum(r['recovery_n'] for r in have)
        rec = (
            sum(r['recovery'] * r['recovery_n'] for r in have if r['recovery_n'])
            / rec_n
            if rec_n
            else None
        )
        restarts = sum(r['restarts'] * r['n'] for r in have) / n
        note = '' if len(have) == 3 else ' % planning and navigation only'
        tex.append(
            f"{vname} & {k}/{n} & {num(rec, '.1f', '--')} & {restarts:.2f} & {wall:.0f} \\\\{note}"
        )
    open(f'{root}/tables.tex', 'w').write('\n'.join(tex) + '\n')


if __name__ == '__main__':
    main()
